"""Rebuild frozen solid-vector inputs from their declared provenance.

python vector_inputs.py studies/music-navigation/paired/a.json /private/icons \
  --fonts /private/Library/Fonts --radio /private/radio-public-export.svg

Fonts, source SVG and artwork stay private. This command generates vectors
only; source imagery/artwork still follow the study's separate input hashes.
Every generated byte stream must match its frozen SHA256 before it is saved.
"""
from pathlib import Path
import argparse,hashlib,json,xml.etree.ElementTree as ET
from font_vector import export
from vector_shapes import svg,library_variant


def digest(raw):return hashlib.sha256(raw).hexdigest()


def rebuild(layer,fonts=None,radio=None):
    meta=layer.get('vector_provenance',{});name=layer['vector_asset']
    if 'font_file' in meta:
        assert fonts is not None,'Original private font directory is required'
        font=Path(fonts)/meta['font_file']
        assert digest(font.read_bytes())==meta['font_sha256'],'Changed source font'
        raw,_=export(font,meta.get('glyph'),meta.get('text'),meta.get('size_pt'))
        raw=raw.encode()
    elif meta.get('generator')=='vector_shapes.library_variant':
        t=meta['note_transform'];raw=library_variant(t['dx'],t['dy'],t['scale'])
    elif name=='radio.svg':
        assert radio is not None,'Pinned original Radio SVG is required'
        original=Path(radio).read_bytes();assert digest(original)==meta['source_sha256'],'Changed source SVG'
        root=ET.fromstring(original);width=root.attrib.pop('width');height=root.attrib.pop('height')
        root.set('viewBox',f'0 0 {width} {height}');raw=ET.tostring(root)
    else:
        family={'home.svg':'home','search.svg':'search','new.svg':'new-grid','library.svg':'library-stack','selection.svg':'selected-backing'}
        assert name in family,f'No declared generator for {name}'
        raw=svg(family[name]).encode()
    assert digest(raw)==layer['vector_sha256'],f'Rebuilt vector differs: {name}'
    return raw


def main():
    ap=argparse.ArgumentParser();ap.add_argument('case',type=Path);ap.add_argument('out',type=Path)
    ap.add_argument('--fonts',type=Path);ap.add_argument('--radio',type=Path);a=ap.parse_args()
    case=json.loads(a.case.read_text());assets={}
    for layer in case.get('foreground_layers',[]):
        if 'vector_asset' not in layer:continue
        raw=rebuild(layer,a.fonts,a.radio);name=layer['vector_asset']
        assert name not in assets or assets[name]==raw,'Contradictory repeated vector provenance'
        assets[name]=raw
    assert assets,'No solid-vector inputs declared'
    # Finish all validation before touching the destination.
    for name,raw in assets.items():
        destination=a.out/name
        assert not destination.exists() or destination.read_bytes()==raw,f'Do not overwrite a different asset: {name}'
    a.out.mkdir(parents=True,exist_ok=True)
    for name,raw in assets.items():(a.out/name).write_bytes(raw)
    print(json.dumps(dict(case=case['id'],vectors={name:digest(raw) for name,raw in assets.items()})),flush=True)


if __name__=='__main__':main()
